/**
 * The [•] mark: lock-on brackets around a dot. Grey dot when idle, red when
 * locked; switching to locked snaps the brackets in with the loader's
 * overshoot curve (none under prefers-reduced-motion). Vector source:
 * lockin-brand/svg/logo-mark-*.svg.
 *
 * tone: "ink" brackets on light surfaces, "cream" on dark ones.
 */
export type LockState = "idle" | "locked";
export type LockTone = "ink" | "cream";

type LockMarkProps = {
  state: LockState;
  size?: number;
  tone?: LockTone;
  className?: string;
  /** Accessible name. Without one the mark is decorative. */
  title?: string;
};

export function LockMark({ state, size = 32, tone = "ink", className = "", title }: LockMarkProps) {
  return (
    <svg
      viewBox="-50 -50 100 100"
      width={size}
      height={size}
      className={`lockmark lockmark-${tone} lockmark-${state} ${className}`}
      data-state={state}
      role={title ? "img" : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
      focusable="false"
    >
      <path className="lm-c lm-tl" d="M-35 -17V-35H-17" />
      <path className="lm-c lm-tr" d="M17 -35H35V-17" />
      <path className="lm-c lm-br" d="M35 17V35H17" />
      <path className="lm-c lm-bl" d="M-17 35H-35V17" />
      <circle className="lm-dot" r="10" />
    </svg>
  );
}

